def lam_sach_kd(d):
    nhat_ky = [("Ban đầu", len(d))]

    d = d.dropna(subset=["ngay", "ma_ch"])
    nhat_ky.append(("Bỏ dòng thiếu ngày/mã CH", len(d)))

