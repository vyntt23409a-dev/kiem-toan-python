"""#Lập một phần mềm tính khấu hao tài sản cố định theo PP đường thẳng. Kết quả hiển thị: khấu hao từng, khấu hao lũy kế, giá trị còn lại của tài sản."""

class PPE:
    def __init__(self, asset_name, cost, residual_value, useful_life):
        if cost <= 0:
            raise ValueError("Nguyên giá tài sản phải lớn hơn 0!")
        if residual_value < 0:
            raise ValueError("Giá trị thanh lý ước tính không được âm!")
        if residual_value >= cost:
            raise ValueError("Giá trị thanh lý không thể lớn hơn hoặc bằng nguyên giá!")
        if useful_life <= 0:
            raise ValueError("Thời gian sử dụng hữu ích phải lớn hơn 0 năm!")

        self.asset_name = asset_name
        self.cost = cost
        self.residual_value = residual_value
        self.useful_life = useful_life

    @property
    def annual_depreciation(self):
        """Tính mức khấu hao hàng năm theo phương pháp đường thẳng"""
        return (self.cost - self.residual_value) / self.useful_life

    def generate_schedule(self):
        """Tính toán và trả về bảng khấu hao qua các năm"""
        schedule = []
        accumulated = 0.0
        carrying_amount = self.cost
        annual_dep = self.annual_depreciation

        for year in range(1, self.useful_life + 1):
            accumulated += annual_dep
            carrying_amount -= annual_dep
            schedule.append({
                "year": year,
                "annual_depreciation": annual_dep,
                "accumulated_depreciation": accumulated,
                "remaining_value": max(0.0, carrying_amount)
            })
        return schedule

    def display_schedule(self):
        """Hiển thị bảng khấu hao trực quan"""
        print(f"===================================")
        print(f" BẢNG KHẤU HAO TÀI SẢN: {self.asset_name.upper()}")
        print(f" Nguyên giá: {self.cost:,.2f} VNĐ")
        print(f" Giá trị thanh lý ước tính: {self.residual_value:,.2f} VNĐ")
        print(f" Thời gian sử dụng: {self.useful_life} năm")
        print(f" Mức khấu hao hàng năm: {self.annual_depreciation:,.2f} VNĐ")
        print(f"===================================")
        print(f"{'Năm':<6} | {'Khấu hao năm':<18} | {'Khấu hao lũy kế':<20} | {'Giá trị còn lại':<18}")
        print("-" * 70)

        # Hiển thị năm 0 (Giá trị ban đầu)
        print(f"{0:<6} | {'0.00':<18} | {'0.00':<20} | {self.cost:>18,.2f}")

        schedule = self.generate_schedule()
        for row in schedule:
            print(f"{row['year']} | {row['annual_depreciation']:>18,.2f} | {row['accumulated_depreciation']:>20,.2f} | {row['remaining_value']:>18,.2f}")
        print(f"===================================\n")

