class Product:
    def __init__(self, code, name, initial_stock, unit_price):
        if initial_stock < 0:
            raise ValueError("Số lượng tồn ban đầu không được âm!")
        if unit_price < 0:
            raise ValueError("Đơn giá không được âm!")

        self.code = code
        self.name = name
        self.stock = initial_stock
        self.unit_price = unit_price
        self.total_imported = initial_stock  # Xem như ban đầu là nhập kho
        self.total_exported = 0

    def import_stock(self, quantity):
        """Nhập thêm hàng vào kho"""
        if quantity <= 0:
            print(f"[LỖI] Số lượng nhập ({quantity}) phải lớn hơn 0!")
            return False
        self.stock += quantity
        self.total_imported += quantity
        print(f"[THÀNH CÔNG] Nhập thêm {quantity} {self.name}. Tồn kho hiện tại: {self.stock}")
        return True

    def export_stock(self, quantity):
        """Xuất hàng khỏi kho"""
        if quantity <= 0:
            print(f"[LỖI] Số lượng xuất ({quantity}) phải lớn hơn 0!")
            return False
        if quantity > self.stock:
            print(f"[LỖI] Không đủ hàng trong kho! Cần xuất {quantity} nhưng chỉ còn {self.stock} {self.name}.")
            return False
        self.stock -= quantity
        self.total_exported += quantity
        print(f"[THÀNH CÔNG] Xuất {quantity} {self.name}. Tồn kho hiện tại: {self.stock}")
        return True

    @property
    def inventory_value(self):
        """Giá trị hàng tồn kho hiện tại"""
        return self.stock * self.unit_price


