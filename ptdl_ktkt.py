def flatten_dict(d,parent_key="",result=None):
  if result is None:
    result = {}
  for key, value in d.items():
    if parent_key=="":
      new_key=key
    else:
      new_key=parent_key+"."+key
    if isinstance(value,dict):
      flatten_dict(value,new_key,result)
    else:
      result[new_key]=value
  return result
